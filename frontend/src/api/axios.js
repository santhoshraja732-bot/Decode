import axios from 'axios'

// Requests go to /api/* and Vite's dev server proxy forwards them to the
// FastAPI backend at http://localhost:8000 (see vite.config.js). In
// production, set VITE_API_BASE or serve the frontend behind the same
// reverse proxy as the backend.
const api = axios.create({
  baseURL: '/api',
})

api.interceptors.request.use((config) => {
  const token = localStorage.getItem('access_token')
  if (token) {
    config.headers.Authorization = `Bearer ${token}`
  }
  return config
})

api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      localStorage.removeItem('access_token')
      localStorage.removeItem('user')
      if (window.location.pathname !== '/login') {
        window.location.href = '/login'
      }
    }
    return Promise.reject(error)
  }
)

export default api
